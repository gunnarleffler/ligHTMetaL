import { writeFile } from 'node:fs/promises';
import { allThemes, light, dark, themeToCSS } from '../src/polish/themes/index.js';

// Keep this inherited mode contract identical to lightmetal.css. Both stand alone.
const modes = `
[data-lightmetal-theme="light"] { --lightmetal-color-scheme: light; color-scheme: light; }
[data-lightmetal-theme="dark"] { --lightmetal-color-scheme: dark; color-scheme: dark; }
[data-lightmetal-theme="auto"] { --lightmetal-color-scheme: light dark; color-scheme: light dark; }
`;
// Match a theme-* class token, not an unrelated app-theme-* substring. CSS hex
// escapes cover the other HTML class separators: tab, LF, form feed, and CR.
const separators = [' ', '\\9 ', '\\a ', '\\c ', '\\d '];
const themeClass = ['[class^="theme-"]', ...separators.map(space => `[class*="${space}theme-"]`)].join(', ');
// An explicit palette (including app-defined theme-* classes) owns its subtree.
const named = `:is(.code, .polish, .lightmarkdown-preview):is(${themeClass})`;
const automatic = `:where(.code, .polish, .lightmarkdown-preview):not(:where(${named}, ${named} *))`;
const categories = ['plain', 'comment', 'keyword', 'string', 'number', 'boolean', 'constant', 'function', 'type', 'variable', 'property', 'operator', 'punctuation', 'tag', 'attribute'];
const automaticCSS = [
  `${automatic} { color-scheme: var(--lightmetal-color-scheme, light dark); }`,
  `${automatic}:where(.code, .polish):not(.lightmarkdown-preview) { color: light-dark(${light.foreground}, ${dark.foreground}); background: light-dark(${light.background}, ${dark.background}); }`,
  ...categories.flatMap(kind => {
    const style = light.tokens[kind] ?? {};
    return [
      `${automatic} { --code-${kind}: light-dark(${style.foreground ?? light.foreground}, ${dark.tokens[kind]?.foreground ?? dark.foreground}); }`,
      `${automatic} .token.${kind} { color: var(--code-${kind}); font-weight: ${style.bold ? '700' : '400'}; font-style: ${style.italic ? 'italic' : 'normal'}; text-decoration: ${style.underline ? 'underline' : 'none'}; }`,
    ];
  }),
].join('\n');

// Theme data is authoritative. Keep the source stylesheet usable without a build.
const css = `/* ligHTMetaL::poliSH — generated by npm run build; edit src/polish/themes/. */
.code, .polish pre {
  white-space: pre;
  overflow: auto;
  tab-size: 2;
  font-family: ui-monospace, SFMono-Regular, Consolas, monospace;
}
${modes}
${automaticCSS}
${allThemes.map(theme => themeToCSS(theme) + `\n.code.theme-${theme.name}, .polish.theme-${theme.name} { --lightmetal-color-scheme: ${theme.appearance}; }`).join('\n')}
`;
await writeFile(new URL('../src/polish.css', import.meta.url), css);
